def load_history():
    if not HISTORY_FILE.exists():
        return []
    try:
        data = json.loads(HISTORY_FILE.read_text(encoding="utf-8"))
        if not isinstance(data, list):
            raise ValueError("История должна быть списком")
        return data
    except Exception as exc:
        print(f"ОШИБКА: история публикаций повреждена: {exc}")
        sys.exit(1)

def main():
    if not TOKEN:
        raise RuntimeError("Не задан секрет VK_ACCESS_TOKEN")
    history = load_history()
    used_titles = {x.get("title") for x in history}
    used_texts = {x.get("text") for x in history}
    today = datetime.now(TZ).date().isoformat()
    slot = os.getenv("POST_SLOT", "manual")
    if any(x.get("date") == today and x.get("slot") == slot for x in history):
        print(f"Публикация за {today}, слот {slot}, уже есть. Пропускаю.")
        return

    available = [m for m in MOVIES if m[0] not in used_titles]
    if not available:
        raise RuntimeError("Каталог рекомендаций исчерпан. Добавьте новые фильмы и сериалы в MOVIES.")
    random.SystemRandom().shuffle(available)
    selected = None
    post = None
    for title, genre, hook in available:
        tags = random.SystemRandom().sample(HASHTAGS[genre], 3)
        sentence = f"{random.choice(OPENERS)} «{title}» — {hook}{random.choice(ENDINGS)}"
        text = sentence + "\n\n" + " ".join(tags)
        if text not in used_texts:
            selected, post = (title, genre), text
            break
    if not selected:
        raise RuntimeError("Не удалось собрать уникальный текст.")

    response = requests.post(
        "https://api.vk.com/method/wall.post",
        data={"access_token": TOKEN, "v": API_VERSION, "owner_id": -GROUP_ID,
              "from_group": 1, "message": post},
        timeout=30,
    )
    payload = response.json()
    if "error" in payload:
        raise RuntimeError(f"VK API error: {payload['error']}")
    post_id = payload.get("response", {}).get("post_id")
    if not post_id:
        raise RuntimeError(f"VK не вернул post_id: {payload}")
    history.append({"date": today, "slot": slot, "title": selected[0],
                    "genre": selected[1], "text": post, "post_id": post_id})
    HISTORY_FILE.write_text(json.dumps(history, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"УСПЕХ: опубликовано «{selected[0]}», post_id={post_id}")
    print(post)

if __name__ == "__main__":
    main()
